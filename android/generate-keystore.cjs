#!/usr/bin/env node

/**
 * Generate the Android release keystore. Works on Windows, macOS and Linux.
 *
 * This key is the app's identity on Google Play. Play accepts an update only if
 * it is signed with the same key as the version before it, so losing the file or
 * its password ends the ability to update the app at all -- there is no recovery
 * and no way to ask Google to make an exception. Back both up somewhere that is
 * not this folder.
 *
 * The password used to be written into this file as "rutiini2024", which meant
 * every copy of the project shared one publicly readable password. The .jks is
 * kept out of version control, so that alone did not hand anyone the key, but a
 * known password removes the only protection left if the file is ever mislaid --
 * in a backup, a zip, an email attachment -- and whoever held it could publish an
 * update to the real app. A password is now taken from the environment, or
 * generated at random and shown once.
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { execSync } = require('child_process');

const keystorePath = path.join(__dirname, 'app', 'rutiini-release.jks');
const keystorePropsPath = path.join(__dirname, 'keystore.properties');

console.log('\n=== Android release keystore ===\n');

/** keytool from JAVA_HOME when it is set, otherwise from PATH. */
function keytool() {
  const javaHome = process.env.JAVA_HOME;
  if (!javaHome) {
    // Falling back to the bare name was the point: joining an unset JAVA_HOME
    // produced the relative path "java/bin/keytool.exe", which exists nowhere,
    // so the script failed on any Windows machine without JAVA_HOME rather than
    // using the keytool already on PATH.
    return 'keytool';
  }
  const name = process.platform === 'win32' ? 'keytool.exe' : 'keytool';
  return path.join(javaHome, 'bin', name);
}

const keystoreExists = fs.existsSync(keystorePath);
const propsExist = fs.existsSync(keystorePropsPath);

if (keystoreExists && propsExist) {
  console.log('Keystore and keystore.properties are already in place. Nothing to do.');
  console.log(`  ${keystorePath}`);
  process.exit(0);
}

if (keystoreExists && !propsExist) {
  // The password cannot be read back out of the keystore, and writing the wrong
  // one produces a build that fails to sign with an error that does not say why.
  const supplied = process.env.KEYSTORE_PASSWORD;
  if (!supplied) {
    console.error('The keystore exists but keystore.properties does not, so the');
    console.error('password for it is needed and cannot be recovered from the file:\n');
    console.error('  Windows:      set KEYSTORE_PASSWORD=your-password');
    console.error('  PowerShell:   $env:KEYSTORE_PASSWORD = "your-password"');
    console.error('  macOS/Linux:  export KEYSTORE_PASSWORD=your-password\n');
    console.error('then run this again. A keystore generated by an older version of');
    console.error('this script used the password rutiini2024.\n');
    process.exit(1);
  }
  // Check it before writing it. A wrong password here is not discovered until
  // Gradle tries to sign, where it surfaces as a failure that does not say the
  // password is the problem.
  if (!opensKeystore(supplied)) {
    console.error('That password does not open the existing keystore:');
    console.error(`  ${keystorePath}\n`);
    console.error('Nothing was written. Try again with the right one.\n');
    process.exit(1);
  }

  writeProperties(supplied);
  console.log('\nkeystore.properties written for the existing keystore.\n');
  process.exit(0);
}

// No keystore yet: make one.
const password = process.env.KEYSTORE_PASSWORD || crypto.randomBytes(24).toString('base64url');
const generated = !process.env.KEYSTORE_PASSWORD;

console.log('Generating a new signing key...');
try {
  execSync(
    `"${keytool()}" -genkeypair -v -keystore "${keystorePath}"` +
      ' -keyalg RSA -keysize 2048 -validity 10000 -alias rutiini-key' +
      ` -storepass "${password}" -keypass "${password}"` +
      ' -dname "CN=Rutiini, OU=Daycare, O=Rutiini, L=Finland, S=Finland, C=FI"',
    { stdio: 'inherit', shell: true },
  );
} catch (error) {
  console.error('\nCould not generate the keystore:', error.message);
  console.error('Install Android Studio or a JDK, and make sure keytool is on PATH');
  console.error('or that JAVA_HOME points at the JDK.\n');
  process.exit(1);
}

writeProperties(password);

console.log('\n=== Keep this safe ===\n');
if (generated) {
  console.log(`  Password: ${password}\n`);
  console.log('  This is shown once and is not printed again. It is also in');
  console.log(`  ${keystorePropsPath},`);
  console.log('  which is deliberately not in version control.\n');
}
console.log('  Back up both the password and');
console.log(`  ${keystorePath}`);
console.log('  somewhere outside this folder. Google Play accepts an update only');
console.log('  if it is signed with this same key: lose it and the app can never');
console.log('  be updated again.\n');

/** Whether this password actually opens the keystore. */
function opensKeystore(pw) {
  try {
    execSync(`"${keytool()}" -list -keystore "${keystorePath}" -storepass "${pw}"`, {
      stdio: 'ignore',
      shell: true,
    });
    return true;
  } catch {
    return false;
  }
}

function writeProperties(pw) {
  fs.writeFileSync(
    keystorePropsPath,
    ['storeFile=app/rutiini-release.jks', `storePassword=${pw}`, 'keyAlias=rutiini-key', `keyPassword=${pw}`, ''].join('\n'),
  );
}
